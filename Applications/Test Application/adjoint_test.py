"""Run adjoint advection-diffusion test on Test Application mesh and export ParaView time series.

Assumptions:
- A Gaussian source is used to generate forward state snapshots.
- Desired data u_d is generated by a second forward solve (same model, different source center).
- Adjoint snapshots are exported in forward time-index order (t_0 to t_N),
  even though the adjoint equation is solved backward in time.

Usage:
    python3 adjoint_test.py

Outputs:
    Applications/Test Application/adjoint_output/
      - adjoint.pvd                 (open this in ParaView)
      - adjoint_0000.vtu, ...       (time-step data files)
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
import sys

import meshio
import numpy as np


APP_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = APP_DIR.parents[1]
SOLVER_DIR = PROJECT_ROOT / "Src" / "Solvers"

if str(APP_DIR) not in sys.path:
    sys.path.append(str(APP_DIR))

_FORWARD_SOLVER_FILE = SOLVER_DIR / "adv_diff_forward.py"
_FORWARD_SOLVER_SPEC = importlib.util.spec_from_file_location(
    "adv_diff_forward",
    _FORWARD_SOLVER_FILE,
)
if _FORWARD_SOLVER_SPEC is None or _FORWARD_SOLVER_SPEC.loader is None:
    raise ImportError(f"Could not load forward solver module from {_FORWARD_SOLVER_FILE}")
_FORWARD_SOLVER_MODULE = importlib.util.module_from_spec(_FORWARD_SOLVER_SPEC)
_FORWARD_SOLVER_SPEC.loader.exec_module(_FORWARD_SOLVER_MODULE)
adv_diff_dyn = _FORWARD_SOLVER_MODULE.adv_diff_dyn

_ADJOINT_SOLVER_FILE = SOLVER_DIR / "adv_diffusion_adjoint.py"
_ADJOINT_SOLVER_SPEC = importlib.util.spec_from_file_location(
    "adv_diffusion_adjoint",
    _ADJOINT_SOLVER_FILE,
)
if _ADJOINT_SOLVER_SPEC is None or _ADJOINT_SOLVER_SPEC.loader is None:
    raise ImportError(f"Could not load adjoint solver module from {_ADJOINT_SOLVER_FILE}")
_ADJOINT_SOLVER_MODULE = importlib.util.module_from_spec(_ADJOINT_SOLVER_SPEC)
_ADJOINT_SOLVER_SPEC.loader.exec_module(_ADJOINT_SOLVER_MODULE)
adv_diffusion_adjoint = _ADJOINT_SOLVER_MODULE.adv_diffusion_adjoint

from mesh_data_config import build_mesh_data


def source_func(x: float, y: float) -> float:
    xc = 0.9
    yc = 0.2
    sigma2 = 0.005
    return float(np.exp(-((x - xc) ** 2 + (y - yc) ** 2) / sigma2))


def desired_source_func(x: float, y: float) -> float:
    """Reference source used to generate forward-based desired data u_d."""
    xc = 0.7
    yc = 0.2
    sigma2 = 0.005
    return float(np.exp(-((x - xc) ** 2 + (y - yc) ** 2) / sigma2))


def write_pvd(pvd_path: Path, entries: list[tuple[float, str]]) -> None:
    """Write a ParaView collection file that indexes all VTU time steps."""
    lines = [
        '<?xml version="1.0"?>',
        '<VTKFile type="Collection" version="0.1" byte_order="LittleEndian">',
        '  <Collection>',
    ]
    for t, rel_file in entries:
        lines.append(f'    <DataSet timestep="{t:.12g}" group="" part="0" file="{rel_file}"/>')
    lines.extend(['  </Collection>', '</VTKFile>'])
    pvd_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    mesh_data = build_mesh_data()

    coord = np.asarray(mesh_data["coord"], dtype=np.float64)
    connections = np.asarray(mesh_data["connections"], dtype=int)

    npoin = coord.shape[0]
    nelem = connections.shape[0]

    lx = 1.0
    ly = 0.4

    ngauss = 3
    k = 0.1
    vx = 0.1
    vy = 0.0
    dt = 1.0e-4
    tfinal = 0.02
    jprint = 1
    eta1 = 1.0

    with np.errstate(divide="ignore", over="ignore", invalid="ignore"):
        state_out = adv_diff_dyn(
            npoin=npoin,
            nelem=nelem,
            ngauss=ngauss,
            lx=lx,
            ly=ly,
            k=k,
            vx=vx,
            vy=vy,
            dt=dt,
            tfinal=tfinal,
            jprint=jprint,
            coord=coord,
            connections=connections,
            source_func=source_func,
            mesh_data=mesh_data,
            dirichlet_tags=["left"],
        )

        # u_d is forward-generated from the same PDE model (separate reference run).
        desired_state_out = adv_diff_dyn(
            npoin=npoin,
            nelem=nelem,
            ngauss=ngauss,
            lx=lx,
            ly=ly,
            k=k,
            vx=vx,
            vy=vy,
            dt=dt,
            tfinal=tfinal,
            jprint=jprint,
            coord=coord,
            connections=connections,
            source_func=desired_source_func,
            mesh_data=mesh_data,
            dirichlet_tags=["left"],
        )

        adjoint_out = adv_diffusion_adjoint(
            npoin=npoin,
            nelem=nelem,
            ngauss=ngauss,
            lx=lx,
            ly=ly,
            k=k,
            vx=vx,
            vy=vy,
            dt=dt,
            tfinal=tfinal,
            jprint=jprint,
            coord=coord,
            connections=connections,
            state_out=state_out,
            ud=desired_state_out,
            eta1=eta1,
            st_ngauss=3,
            mesh_data=mesh_data,
            dirichlet_tags=["left"],
            measurement_boundary=mesh_data.get("measurement_boundary", "right"),
        )

    right_nodes = np.asarray(
        mesh_data["boundary_nodes_by_name"].get(
            mesh_data.get("measurement_boundary", "right"), np.array([], dtype=int)
        ),
        dtype=int,
    )
    dirichlet_nodes = np.asarray(
        mesh_data["boundary_nodes_by_name"].get("left", np.array([], dtype=int)),
        dtype=int,
    )
    all_nodes = np.arange(npoin, dtype=int)
    interior_nodes = np.setdiff1d(all_nodes, np.unique(np.concatenate([right_nodes, dirichlet_nodes])))

    print("adjoint first norm:", np.linalg.norm(adjoint_out[0]))
    print("adjoint final norm:", np.linalg.norm(adjoint_out[-1]))
    print("adjoint first max on right boundary:", np.max(adjoint_out[0, right_nodes]))
    print("adjoint first max in interior:", np.max(adjoint_out[0, interior_nodes]))

    out_dir = APP_DIR / "adjoint_output"
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("adjoint_*.vtu"):
        stale.unlink()

    if coord.shape[1] == 2:
        points = np.column_stack([coord, np.zeros(npoin)])
    else:
        points = coord

    cells = [("triangle", connections)]

    nframes = adjoint_out.shape[0]
    times = np.arange(nframes, dtype=np.float64) * dt * jprint

    pvd_entries: list[tuple[float, str]] = []
    for iframe in range(nframes):
        vtu_name = f"adjoint_{iframe:04d}.vtu"
        vtu_path = out_dir / vtu_name

        mesh = meshio.Mesh(
            points=points,
            cells=cells,
            point_data={"p": adjoint_out[iframe]},
        )
        meshio.write(vtu_path, mesh)
        pvd_entries.append((float(times[iframe]), vtu_name))

    pvd_path = out_dir / "adjoint.pvd"
    write_pvd(pvd_path, pvd_entries)
    print(f"Adjoint output directory: {out_dir}")
    print(f"Open this file in ParaView: {pvd_path}")


if __name__ == "__main__":
    main()
